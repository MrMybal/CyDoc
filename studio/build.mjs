import { build } from 'esbuild';
import { mkdir, cp, writeFile, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildExample } from './build-example.mjs';
import { studioThemes, studioThemeCss } from './theme-catalog.mjs';
const root = dirname(fileURLToPath(import.meta.url));
await mkdir(resolve(root, 'dist'), { recursive: true });
await build({ entryPoints: [resolve(root, 'web/app.mjs')], outfile: resolve(root, 'dist/studio.js'), bundle: true, format: 'iife', target: 'es2022', minify: true, legalComments: 'external' });
await build({ entryPoints: [resolve(root, 'web/preview.mjs')], outdir: resolve(root, 'dist'), bundle: true, splitting: true, format: 'esm', target: 'es2022', minify: true, legalComments: 'external', chunkNames: 'chunks/[name]-[hash]' });
for (const file of ['index.html', 'preview.html']) await cp(resolve(root, 'web', file), resolve(root, 'dist', file));
await cp(resolve(root, '../src/viewer.css'), resolve(root, 'dist/reader.css'));
await cp(resolve(root, 'web/studio.css'), resolve(root, 'dist/studio.css'));
const catalog = await studioThemes();
await writeFile(resolve(root, 'dist/themes.json'), JSON.stringify(catalog, null, 2));
await writeFile(resolve(root, 'dist/themes.css'), studioThemeCss(catalog));
await buildExample(resolve(root, 'dist/example'));
await cp(resolve(root, '../dist/site'), resolve(root, 'dist/help'), { recursive: true });
await build({entryPoints:[resolve(root,'web/reader-appearance.mjs')],outfile:resolve(root,'dist/help/DocData/studio-appearance.js'),bundle:true,format:'iife',target:'es2022',minify:true});
const manual = resolve(root,'dist/help/Documentation.html');
await writeFile(manual,(await readFile(manual,'utf8')).replace('</head>','<script defer src="DocData/studio-appearance.js"></script></head>'));
console.log('CyDoc Studio built.');
